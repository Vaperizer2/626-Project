def tex_escape(s: str) -> str:
    return (str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
            .replace("_", r"\_").replace("#", r"\#").replace("~", r"\textasciitilde{}"))


def write(name: str, body: str) -> None:
    (OUT / name).write_text(f"% generated by docs/itri626_report/make_tables.py -- do not edit by hand\n{body}\n")


def f3(x):
    return f"{x:.3f}"


def macro_f1(y, p, k=20):
    cm = np.bincount(y * k + p, minlength=k * k).reshape(k, k)
    tp = np.diag(cm).astype(float)
    prec_d, rec_d = cm.sum(0), cm.sum(1)
    prec = np.divide(tp, prec_d, out=np.zeros(k), where=prec_d > 0)
    rec = np.divide(tp, rec_d, out=np.zeros(k), where=rec_d > 0)
    d = prec + rec
    f1 = np.divide(2 * prec * rec, d, out=np.zeros(k), where=d > 0)
    return f1.mean()


