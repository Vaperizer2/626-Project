NUM: dict[str, tuple[str, str]] = {}   # macro name -> (value, source)


def num(name: str, value, source: str, fmt: str | None = None) -> str:
    s = format(value, fmt) if fmt else str(value)
    assert name.isalpha(), name
    assert name not in NUM, name
    NUM[name] = (s, source)
    return s


